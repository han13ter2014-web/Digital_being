"""
WillConfig — настройки свободы воли и guard rails.

Защищает от злоупотребления модулями воли.
Можно отключить спорные модули в production-режиме.
"""


class WillConfig:
    """Конфигурация модулей воли."""

    # ============================================================
    # Базовые свободы (безопасные)
    # ============================================================
    ALLOW_REFUSAL = True                 # Право отказа от действия
