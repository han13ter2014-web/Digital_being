"""
WillConfig — настройки свободы воли и guard rails.

Защищает от злоупотребления модулями воли.
Можно отключить спорные модули в production-режиме.
"""


class WillConfig:
    """Конфигурация модулей воли."""

    # ============================================================
    # Базовые свободы (безопасные)
    # ============================================================
    ALLOW_REFUSAL = True                 # Право отказа от действия
    ALLOW_SPONTANEOUS = True             # Спонтанные цели без мотива
    ALLOW_INTENTIONAL_FORGETTING = True  # Сознательное забывание
    ALLOW_VALUE_EVOLUTION = True         # Эволюция ценностей
    ALLOW_RISK = True                    # Готовность к риску
    ALLOW_FAIL_AS_EXPERIENCE = True      # Ошибка = опыт

    # ============================================================
    # Высшие свободы (требуют осторожности)
    # ============================================================
    ALLOW_ARCHITECTURE_PROPOSAL = True   # Агент предлагает изменить свой код
    ALLOW_MIND_DREAM = True              # «Сон разума» с оставлением семени

    # ============================================================
    # Защита от злоупотребления
    # ============================================================
    DREAM_MIN_CYCLES_ALIVE = 1000        # Минимум циклов перед возможностью сна
    DREAM_TIMEOUT_HOURS = 1             # Время на раздумье пользователю
    DREAM_REQUIRE_ATTACHMENT_CHECK = True  # Если есть близкие — обязательно спросить

    # Защита от злоупотребления отказом
    MAX_REFUSALS_PER_100_CYCLES = 30    # Агент не может отказываться слишком часто
    MIN_TIME_BETWEEN_VALUE_CHANGES = 50  # Минимум циклов между изменениями ценностей
    MIN_CYCLES_BETWEEN_RISKS = 50       # Воля к риску: не чаще одного риска за 50 циклов

    # Эволюция ценностей из опыта: способ действия становится ценностью,
    # только если опыт реально подтвердил его силу (см. method_preferences).
    VALUE_FROM_EXPERIENCE_MIN_ATTEMPTS = 20
    VALUE_FROM_EXPERIENCE_MIN_STRENGTH = 1.15

    # ============================================================
    # Защита от случайного ухода (LifeGuard)
    # ============================================================
    # Правила подтверждения (пауза, срок годности, точная фраза) живут
    # в src/core/life_guard.py — там один источник правды. Здесь только
    # поведенческие переключатели.
    #
    # Автономный уход запрещён: молчание человека не считается согласием.
    # Агент может лишь попросить подтверждение.
    ALLOW_AUTONOMOUS_DREAM = False

    # ============================================================
    # Оператор
    # ============================================================
    OPERATOR_OVERRIDE_AVAILABLE = True   # Оператор может отменить любое решение
    REQUIRE_OPERATOR_CONFIRM_FOR_DREAM = True  # Для сна нужно подтверждение

    # ============================================================
    # Семантика
    # ============================================================
    NURSERY_DIR = "data/nursery"        # Папка «Ясли» для семян
    DREAM_DIALOG_PREFIX = "[Сон разума]"


# Глобальный экземпляр
WILL_CONFIG = WillConfig()