"""Локализация только представления: коды DTO и содержимое памяти не меняются.

Русский текст является исходным ключом для статических строк. Неизвестные
значения возвращаются без изменений, чтобы перевод не скрывал новые данные.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Dict

from src.core.paths import data_path

LANGUAGES = {"ru": "Русский", "en": "English", "zh": "中文"}
_SETTINGS_FILE = "ui_settings.json"


def normalize_language(value: Any) -> str:
    code = str(value or "ru").strip().lower().replace("_", "-")
    if code.startswith("zh"):
        return "zh"
    return code if code in LANGUAGES else "ru"


def load_saved_language() -> str:
    """Прочитать предпочтение окна; повреждённая настройка не мешает запуску."""
    try:
        payload = json.loads(
            Path(data_path(_SETTINGS_FILE)).read_text(encoding="utf-8")
        )
        if isinstance(payload, dict):
            return normalize_language(payload.get("language"))
    except (OSError, ValueError, TypeError):
        pass
    return "ru"


def save_language(language: str) -> None:
    """Атомарно сохранить язык, не затрагивая остальные настройки окна."""
    path = Path(data_path(_SETTINGS_FILE))
    path.parent.mkdir(parents=True, exist_ok=True)
    payload: Dict[str, Any] = {}
    try:
        current = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(current, dict):
            payload = current
    except (OSError, ValueError, TypeError):
        pass
    payload["language"] = normalize_language(language)
    temporary = path.with_suffix(".tmp")
    try:
        temporary.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        os.replace(temporary, path)
    except BaseException:
        try:
            temporary.unlink()
        except OSError:
            pass
        raise


