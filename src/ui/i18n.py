def text(value: Any, language: str = "ru") -> str:
    """Перевести известную статическую фразу, неизвестную вернуть как есть."""
    raw = str(value)
    lang = normalize_language(language)
    if lang == "ru":
        return raw
    return TEXTS[lang].get(raw, raw)


def language_json() -> str:
    """Данные для веб-представления; ``<`` экранировано на границе script."""
    payload = {
        "values": VALUE_LABELS,
        "fields": FIELD_LABELS,
        "texts": TEXTS,
        "actions": ACTION_PHRASES,
        "valueCodes": {russian: code for code, russian in VALUE_LABELS["ru"].items()},
        "fieldCodes": {russian: code for code, russian in FIELD_LABELS["ru"].items()},
    }
    return json.dumps(payload, ensure_ascii=False, separators=(",", ":")).replace(
        "<", "\\u003c"
    )


