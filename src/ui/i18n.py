def _code_from_russian(value: str, labels: Dict[str, Dict[str, str]]) -> str:
    for code, russian in labels["ru"].items():
        if value == russian:
            return code
    return value


def value_label(value: Any, language: str = "ru") -> str:
    raw = str(value)
    code = _code_from_russian(raw, VALUE_LABELS)
    lang = normalize_language(language)
    return VALUE_LABELS[lang].get(code) or VALUE_LABELS["ru"].get(code) or raw


def field_label(value: Any, language: str = "ru") -> str:
    raw = str(value)
    code = _code_from_russian(raw, FIELD_LABELS)
    lang = normalize_language(language)
    return FIELD_LABELS[lang].get(code) or FIELD_LABELS["ru"].get(code) or raw


def action_phrase(action: Any, language: str = "ru") -> str:
    raw = str(action or "")
    if not raw:
        return text("занятие", language)
    lang = normalize_language(language)
    return (
        ACTION_PHRASES[lang].get(raw)
        or ACTION_PHRASES["ru"].get(raw)
        or value_label(raw, lang)
    )


