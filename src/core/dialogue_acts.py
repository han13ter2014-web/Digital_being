@dataclass(frozen=True)
class DialogueAct:
    """Распознанный акт пользователя.

    ``matched_marker`` — конкретный маркер, по которому решено; для
    ACT_UNKNOWN всегда пустой. Поле нужно тестам и журналам: решение
    маршрутизации должно быть проверяемым, а не магией.
    """

    kind: str
    matched_marker: str = ""


def classify_user_text(text, learned=None) -> DialogueAct:
    """Определить речевой акт пользователя по таблице маркеров.

    Приоритет: явная ответная формула → ACT_ANSWER; вопрос о сущности →
    ACT_ASK_ABOUT_SELF; социальная фраза → ACT_SOCIAL; иначе
    ACT_UNKNOWN (старая маршрутизация без изменений).

    «Собеседник-7»: необязательный ``learned`` — отображение
    {нормализованная фраза: акт} из DialogueLearning. Обученные маркеры
    проверяются ПОСЛЕ статических таблиц (рукописное сильнее
    обученного) и ведут только на существующие акты.

    Сравнение идёт по нормализованному тексту: нижний регистр, сжатые
    пробелы. Пунктуация не вырезается — маркеры в таблицах уже содержат
    только буквы и пробелы, а «ответ:» с двоеточием ловит и «Ответ:»,
    и «ответ:».
    """
    normalized = " ".join(str(text or "").lower().split())
    if not normalized:
        return DialogueAct(ACT_UNKNOWN)

    for marker in _ANSWER_MARKERS:
        if marker in normalized:
            return DialogueAct(ACT_ANSWER, marker)

    for marker in _ABOUT_SELF_MARKERS:
        if marker in normalized:
            return DialogueAct(ACT_ASK_ABOUT_SELF, marker)

    # Вопрос-узнавание имени: тоже вопрос о сущности, до просьб и
    # социальной речи. Ответ строится из актуального имени в Core.
    proposed = extract_identity_check(text)
    if proposed is not None:
        return DialogueAct(ACT_ASK_ABOUT_SELF, proposed)

    # Просьбы о невозможном — после вопросов о себе и до социальной
    # речи. Сравнение по тексту со заменой «ё»→«е» и вынесенными
    # запятыми («Опиши, что чувствуешь?» — та же просьба, что без
    # запятой; запятая не должна ломать фразу).
    if not _REQUEST_GUARD_RE.search(normalized):
        folded = normalized.replace("ё", "е")
        speakable = " ".join(folded.replace(",", " ").split())
        match = (
            _REQUEST_UNACHIEVABLE_RE.search(speakable)
            or _REQUEST_PHRASE_RE.search(speakable)
        )
        if match is not None:
            return DialogueAct(ACT_REQUEST, match.group(0).lower())

    for marker in _SOCIAL_MARKERS:
        if marker in normalized:
            return DialogueAct(ACT_SOCIAL, marker)

    # Обученные маркеры — строго после статических таблиц: рукописное
    # решение разработчика обучение не перекрывает.
    if learned:
        for phrase, kind in learned.items():
            if phrase and phrase in normalized:
                return DialogueAct(kind, phrase)

    return DialogueAct(ACT_UNKNOWN)


def extract_identity_check(text) -> Optional[str]:
    """Вернуть имя из вопроса-узнавания («Ты Афродита?») или None.

    Имя возвращается в написании человека; сравнение с актуальным
    именем — дело вызывающей стороны (casefold). Стоп-слово в любом
    слове «имени» («ты не знаешь кто я», «ты в порядке?») — не
    узнавание.
    """
    normalized = " ".join(str(text or "").split())
    if not normalized:
        return None
    match = _IDENTITY_CHECK_RE.match(normalized)
    if match is None:
        return None
    name = match.group("name").strip()
    if not name:
        return None
    if any(word.casefold() in _IDENTITY_CHECK_STOP for word in name.split()):
        return None
    return name


# Ввод без единой буквы («🙂🙂🙂», «12345», «!!!») — не речь. Раньше
# он уходил в очередь стимулов и изучался как концепт («Не нашел файл
# для '🙂🙂🙂'»). Цифры без букв тоже шум: вопросы сущности ждут
# словесного ответа.
_LETTER_RE = re.compile(r"[а-яёa-z]", re.IGNORECASE)


def is_noise_input(text) -> bool:
    """True, если во вводе нет ни одной буквы (эмодзи, цифры, знаки)."""
    return _LETTER_RE.search(str(text or "")) is None


# Вопросительное слово в начале реплики (с необязательным связующим
# «а/и/ну»): «Что тебе сейчас важно?» — вопрос целиком. Ответ со
# встречным вопросом («Спокойно и тепло. А что тебя занимает?»)
# начинается с утверждения и сюда не попадает.
_QUESTION_START_RE = re.compile(
    r"^(?:а|и|ну)?\s*"
    r"(?:что|чем|чему|чего|как|почему|зачем|когда|кто|кого|кому|кем|"
    r"где|куда|откуда|какой|какая|какое|какие|какого|какому|каким|"
    r"сколько|чей|чья|чьё|чьи|чьего|чьим)\b",
    re.IGNORECASE,
)


def is_question_text(text) -> bool:
    """True, если реплика целиком — вопрос (вопросительное слово + «?»).

    TICKET-5/6 (наблюдатели 2026-11-05): вопрос человека не должен
    закрывать висящий вопрос сущности как «ответ» — иначе «Что тебе
    сейчас важно?» записывалось как «Записал про "обучение"». Ответ
    со встречным вопросом в конце вопросом не считается: он начинается
    с утверждения и остаётся ответом.
    """
    normalized = " ".join(str(text or "").strip().split())
    if not normalized.endswith("?"):
        return False
    return _QUESTION_START_RE.search(normalized) is not None


# «Собеседник-5»: формула «X — это Y» — способ человека объяснить тему
# без прямого вопроса сущности. Тире обязательно: без него «а что это
# за город» и «это важно» ловились бы как определения.
_DEFINITION_RE = re.compile(
    r"^(?P<topic>.{1,60}?)\s*[—–-]\s*это\s+(?P<body>.+?)\s*$",
    re.IGNORECASE,
)

# «Собеседник-6»: вежливые префиксы («Запомни, пожалуйста: оптика —
# это…») не должны попадать в тему. Срезаются до трёх раз подряд,
# поэтому «Пожалуйста, запомни:» тоже разбирается. Совпадение ищется
# после среза; если определение узнавалось и в исходном тексте —
# исходный разбор остаётся запасным.
_POLITE_PREFIX_RE = re.compile(
    r"^(?:пожалуйста\s*,\s*)?"
    r"(?:запомни|запиши|зафиксируй|имей в виду|прими к сведению|"
    r"пожалуйста|кстати|на заметку|для справки)"
    r"\b[,:!]*\s*",
    re.IGNORECASE,
)

# Определение — свидетельство, а не спор: «X — это не Y» знанием не
# записывается.
_DEFINITION_NEGATION_RE = re.compile(r"^(?:не|нет)\b", re.IGNORECASE)

_QUOTE_CHARS = "\"«»„““”"


def extract_definition(text) -> Optional[Tuple[str, str]]:
    """Разобрать «X — это Y» в пару (тема, определение) или None.

    Тема обрезается до 60 символов (regex), кавычки и хвостовая
    пунктуация снимаются. «Собеседник-6»: перед разбором срезаются
    вежливые префиксы («Запомни, пожалуйста:»), вопросительная форма
    («…это Y?» — вопрос, не свидетельство) и отрицание («X — это не Y»)
    определением не считаются. Возвращает None, если формула не узнана
    или одна из частей пуста: нераспознанный текст получает честный
    диалоговый отклик.
    """
    normalized = " ".join(str(text or "").split())
    if not normalized:
        return None
    if normalized.rstrip("!?.,;: ").endswith("?"):
        return None
    candidate = normalized
    for _ in range(3):
        stripped = _POLITE_PREFIX_RE.sub("", candidate, count=1)
        if stripped == candidate:
            break
        candidate = " ".join(stripped.split())
    match = _DEFINITION_RE.match(candidate) or _DEFINITION_RE.match(normalized)
    if match is None:
        return None
    topic = match.group("topic").strip().strip(_QUOTE_CHARS).strip()
    body = match.group("body").strip().rstrip(".!?").strip()
    if not topic or not body:
        return None
    if _DEFINITION_NEGATION_RE.match(body):
        return None
    return topic, body
