    "что ты изучаешь",
    "что изучаешь",
    "что ты сейчас изучаешь",
    # TICKET-4 (наблюдатели 2026-11-05): «Чем ты сейчас занята?» и
    # «Что для тебя сейчас важно?» не узнавались вопросами о сущности —
    # падали в unknown и проглатывались дверью висящего вопроса
    # («Записал про "обучение"»). Устойчивые формы вопроса о её
    # текущем состоянии и делах.
    "чем ты сейчас",
    "что ты сейчас",
    "что для тебя",
