"""
Речевые акты пользователя на входе (участок «Собеседник», ступень 1).

До этого этапа входящий текст имел только две судьбы: «ответ на вопрос
сущности» или «материал для изучения». Социальная речь — приветствие,
«я рядом», протест «уже отвечал» — проглатывалась: живой прогон
2026-11-01 на сущности Тэсс показал «Не нашел файл для 'Я же уже
отвечал тебе.'» и «Ответ записан.» в ответ на социальные реплики.

Здесь — детерминированная таблица маркеров, упорядоченная по
приоритету. Без LLM: это граница архитектуры проекта. Нераспознанное
возвращает ACT_UNKNOWN, и маршрутизация работает по-старому —
безопасный fallback, который ничего не ломает для настоящих ответов.

Реестры сознательно вынесены на уровень модуля: будущие ступени
«Собеседника» (включая возможное саморазвитие таблиц самой сущностью)
расширяют списки, не трогая логику ``classify_user_text``.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Optional, Tuple

ACT_ANSWER = "answer"
ACT_ASK_ABOUT_SELF = "ask_about_self"
ACT_SOCIAL = "social"
ACT_UNKNOWN = "unknown"


# Явные ответные формулы. Проверяются первыми: если человек сам сказал
# «мой ответ», это ответ, даже если дальше идут социальные слова.
_ANSWER_MARKERS = (
    "мой ответ",
    "ответ такой",
    "ответ:",
    "отвечаю:",
    "если коротко",
)


# Вопросы о самой сущности: честный ответ приходит из read-only Core
# (имя, возраст в циклах, текущая тема, что помнит о человеке), а не из
# выдумки. Проверяются после явных ответных формул и раньше социальной
# речи: «чем занимаешься?» — вопрос, а не smalltalk.
_ABOUT_SELF_MARKERS = (
    "как тебя зовут",
    "кто ты",
    "что ты знаешь",
    "чем занимаешься",
    "чем ты занята",
    "чем занята",
    # «что ты сейчас изучаешь?» — живой прогон 2026-11-01: без маркера
    # вопрос о себе уходил в изучение концепта («Не нашел файл для…»).
    "что ты изучаешь",
    "что изучаешь",
    "что ты сейчас изучаешь",
)


# Социальная речь: протест/мета о диалоге, присутствие и обещания,
# приветствия, тепло. Маркеры — фразы целиком, не одиночные слова,
# чтобы «как» в «Спокойно и тепло, как дела у тебя?» не ловило лишнее.
_SOCIAL_MARKERS = (
    # протест / мета о диалоге
    "уже отвечал",
    "уже отвечала",
    "уже говорил",
    "уже говорила",
    "я же",
    "повторяешь",
    "снова спрашиваешь",
    "тот же вопрос",
    "зачем снова",
    # присутствие и обещания
    "я рядом",
    "я здесь",
    "я тут",
    "не переживай",
    "не волнуйся",
    "могу отлучаться",
    "могу пропадать",
    "могу долго не писать",
    "отлучусь",
    "буду молчать",
    "могу молчать",
    "не жди",
    # приветствия и smalltalk
    "привет",
    "здравствуй",
    "доброе утро",
    "добрый день",
    "добрый вечер",
    "доброй ночи",
    "как дела",
    "как ты",
    "как настроение",
    # тепло
    "скучаю",
    "люблю тебя",
    "горжусь тобой",
    "молодец",
    "спасибо тебе",
)


@dataclass(frozen=True)
class DialogueAct:
    """Распознанный акт пользователя.

    ``matched_marker`` — конкретный маркер, по которому решено; для
    ACT_UNKNOWN всегда пустой. Поле нужно тестам и журналам: решение
    маршрутизации должно быть проверяемым, а не магией.
    """

    kind: str
    matched_marker: str = ""


def classify_user_text(text) -> DialogueAct:
    """Определить речевой акт пользователя по таблице маркеров.

    Приоритет: явная ответная формула → ACT_ANSWER; вопрос о сущности →
    ACT_ASK_ABOUT_SELF; социальная фраза → ACT_SOCIAL; иначе
    ACT_UNKNOWN (старая маршрутизация без изменений).

    Сравнение идёт по нормализованному тексту: нижний регистр, сжатые
    пробелы. Пунктуация не вырезается — маркеры в таблицах уже содержат
    только буквы и пробелы, а «ответ:» с двоеточием ловит и «Ответ:»,
    и «ответ:».
    """
    normalized = " ".join(str(text or "").lower().split())
    if not normalized:
        return DialogueAct(ACT_UNKNOWN)

    for marker in _ANSWER_MARKERS:
        if marker in normalized:
            return DialogueAct(ACT_ANSWER, marker)

    for marker in _ABOUT_SELF_MARKERS:
        if marker in normalized:
            return DialogueAct(ACT_ASK_ABOUT_SELF, marker)

    for marker in _SOCIAL_MARKERS:
        if marker in normalized:
            return DialogueAct(ACT_SOCIAL, marker)

    return DialogueAct(ACT_UNKNOWN)


# «Собеседник-5»: формула «X — это Y» — способ человека объяснить тему
# без прямого вопроса сущности. Тире обязательно: без него «а что это
# за город» и «это важно» ловились бы как определения.
_DEFINITION_RE = re.compile(
    r"^(?P<topic>.{1,60}?)\s*[—–-]\s*это\s+(?P<body>.+?)\s*$",
    re.IGNORECASE,
)

_QUOTE_CHARS = "\"«»„““”"


def extract_definition(text) -> Optional[Tuple[str, str]]:
    """Разобрать «X — это Y» в пару (тема, определение) или None.

    Тема обрезается до 60 символов (regex), кавычки и хвостовая
    пунктуация снимаются. Возвращает None, если формула не узнана или
    одна из частей пуста: нераспознанный текст уходит в старую
    маршрутизацию.
    """
    normalized = " ".join(str(text or "").split())
    if not normalized:
        return None
    match = _DEFINITION_RE.match(normalized)
    if match is None:
        return None
    topic = match.group("topic").strip().strip(_QUOTE_CHARS).strip()
    body = match.group("body").strip().rstrip(".!?").strip()
    if not topic or not body:
        return None
    return topic, body
