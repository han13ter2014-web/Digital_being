"""Единое русское описание реальных диалоговых и творческих возможностей.

Просьба человека не обходит арбитр действий: ответ описывает способность,
но не запускает творческое действие и не обещает немедленный результат.
"""

from __future__ import annotations


DRAW_REQUEST_MARKERS = frozenset(
    {
        "нарисуй",
        "нарисуешь",
        "нарисуете",
        "изобрази",
        "изобразишь",
        "изобразите",
    }
)
MUSIC_REQUEST_MARKERS = frozenset(
    {
        "сочини музыку",
        "сочинишь музыку",
        "сочините музыку",
        "сочини мелодию",
        "сочинишь мелодию",
        "сочините мелодию",
        "напиши музыку",
        "напишешь музыку",
        "напишете музыку",
        "напиши мелодию",
        "напишешь мелодию",
        "напишете мелодию",
        "создай мелодию",
        "создашь мелодию",
        "создадите мелодию",
    }
)
SING_REQUEST_MARKERS = frozenset({"спой", "спойте", "споешь", "споете"})

_AUTONOMOUS_CREATIVE_NOTE = (
    "Это одно из моих занятий, а не автоматическое выполнение команды: "
    "действие я выбираю в собственном цикле, поэтому не обещаю начать немедленно."
)


def capabilities_reply() -> str:
    """Перечислить возможности без обещания исполнить каждую просьбу сразу."""
    return (
        "Из просьб я умею: рассказать о себе; процитировать сохранённое знание "
        "о теме; запомнить твоё объяснение в форме «X — это Y»; принять ответ "
        "на свой вопрос и уточнить непонятную реплику. Также я умею рисовать "
        "и сочинять мелодии, но это занятия в собственном цикле, а не "
        "немедленное выполнение команды. Если просьба мне недоступна, я честно "
        "скажу об этом, а не стану выдумывать результат."
    )


def request_reply(matched_marker="") -> str:
    """Ответить по распознанному действию, не вызывая действие из диалога."""
    marker = " ".join(str(matched_marker or "").lower().replace("ё", "е").split())
    if marker in DRAW_REQUEST_MARKERS:
        return f"Я умею рисовать и сохранять свои рисунки. {_AUTONOMOUS_CREATIVE_NOTE}"
    if marker in MUSIC_REQUEST_MARKERS:
        return f"Я умею сочинять мелодии и сохранять их. {_AUTONOMOUS_CREATIVE_NOTE}"
    if marker in SING_REQUEST_MARKERS:
        return (
            "Петь человеческим голосом я не умею. Но я умею сочинять мелодии; "
            "это занятие я выбираю в собственном цикле, а не выполняю как "
            "немедленную команду."
        )
    return (
        "Честно: этого я не умею. Мои действия ограничены собственным телом "
        "и доступными органами. Могу ответить о себе, выучить то, что ты "
        "расскажешь, рисовать и сочинять мелодии в собственном цикле."
    )
